'use strict';

// ---------------------------------------------------------------------------
// Local mock API (jsonplaceholder-style) for manual testing of the request
// editor. Serves in-memory REST resources on port 3999:
//
//   GET    /posts          list a resource
//   GET    /posts/1        read one record
//   POST   /posts          create a record (returns 201 + assigned id)
//   PUT    /posts/1        replace a record
//   PATCH  /posts/1        partially update a record
//   DELETE /posts/1        delete a record
//
// The initial store is loaded from ./mock-data.json, so the sample data is
// retained in the repo and survives restarts (mutations reset on restart).
// The /token and /echo endpoints are kept for the auth-provider flow.
// ---------------------------------------------------------------------------

const http = require('http');
const path = require('path');

const STORE = require(path.join(__dirname, 'mock-data.json'));
const RESOURCES = Object.keys(STORE);

function nextId(list) {
  return list.reduce((max, item) => Math.max(max, Number(item.id) || 0), 0) + 1;
}

// ---------------------------------------------------------------------------
// Static demo payloads: a tiny but valid PDF (offsets computed at build time
// so browsers render it) and a small HTML page for the response Preview tab.
// ---------------------------------------------------------------------------
function buildSamplePdf() {
  const text = 'MockShift sample PDF - generated by the local mock API';
  const objects = {
    1: '<</Type/Catalog/Pages 2 0 R>>',
    2: '<</Type/Pages/Kids[3 0 R]/Count 1>>',
    3: '<</Type/Page/Parent 2 0 R/MediaBox[0 0 612 792]/Contents 4 0 R/Resources<</Font<</F1 5 0 R>>>>>>',
    4: '',
    5: '<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>',
  };
  const stream = `BT\n/F1 24 Tf\n100 700 Td\n(${text}) Tj\nET`;
  objects[4] = `<</Length ${Buffer.byteLength(stream)}>>\nstream\n${stream}\nendstream`;
  let pdf = '%PDF-1.4\n';
  const offsets = {};
  for (const num of [1, 2, 3, 4, 5]) {
    offsets[num] = Buffer.byteLength(pdf);
    pdf += `${num} 0 obj\n${objects[num]}\nendobj\n`;
  }
  const xrefStart = Buffer.byteLength(pdf);
  pdf += 'xref\n0 6\n0000000000 65535 f \n';
  for (const num of [1, 2, 3, 4, 5]) {
    pdf += `${String(offsets[num]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<</Size 6/Root 1 0 R>>\nstartxref\n${xrefStart}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

const SAMPLE_HTML = `<!DOCTYPE html>
<html lang="en">
<head><meta charset="utf-8"><title>MockShift preview</title>
<style>body{font-family:system-ui,sans-serif;padding:24px;background:#f6f7fb;color:#111;line-height:1.5}code{background:#e8ecf8;padding:2px 6px;border-radius:4px}</style></head>
<body>
<h1>Hello from the mock API</h1>
<p>This HTML response is rendered inside the <strong>Preview</strong> tab.</p>
<ul><li>Pretty tab: formatted source</li><li>Raw tab: original bytes</li><li>Download: save as a file</li></ul>
</body></html>`;

function sendJson(res, status, data) {
  res.writeHead(status, { 'Content-Type': 'application/json' });
  res.end(JSON.stringify(data));
}

const server = http.createServer((req, res) => {
  let rawBody = '';
  req.on('data', (c) => (rawBody += c));
  req.on('end', () => {
    const { pathname } = new URL(req.url, 'http://localhost');
    const path = pathname.replace(/\/+$/, '') || '/';
    const method = req.method.toUpperCase();

    // Legacy helpers kept for the auth-provider flow.
    if (path === '/token' && method === 'POST') {
      return sendJson(res, 200, { access_token: 'mock-token-abc123', token_type: 'Bearer' });
    }
    if (path === '/files/sample.pdf' && method === 'GET') {
      const pdf = buildSamplePdf();
      res.writeHead(200, {
        'Content-Type': 'application/pdf',
        'Content-Length': pdf.length,
        'Content-Disposition': 'inline; filename="sample.pdf"',
      });
      return res.end(pdf);
    }
    if (path === '/html' && method === 'GET') {
      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' });
      return res.end(SAMPLE_HTML);
    }
    if (path.startsWith('/echo')) {
      let body = undefined;
      if (rawBody) {
        try { body = JSON.parse(rawBody); } catch { body = rawBody; }
      }
      return sendJson(res, 200, { headers: req.headers, body });
    }

    const [resource, id] = path.split('/').filter(Boolean);
    if (!RESOURCES.includes(resource)) {
      return sendJson(res, 404, { error: 'not found' });
    }
    const list = STORE[resource];

    let payload = null;
    if (rawBody) {
      try { payload = JSON.parse(rawBody); } catch {
        return sendJson(res, 400, { error: 'invalid JSON body' });
      }
    }

    if (method === 'GET') {
      if (id !== undefined) {
        const item = list.find((x) => String(x.id) === id);
        return item ? sendJson(res, 200, item) : sendJson(res, 404, { error: `${resource}/${id} not found` });
      }
      return sendJson(res, 200, list);
    }

    if (method === 'POST') {
      if (id !== undefined) return sendJson(res, 400, { error: 'cannot POST to a specific id' });
      const created = { ...(payload || {}), id: nextId(list) };
      list.push(created);
      return sendJson(res, 201, created);
    }

    if (method === 'PUT' || method === 'PATCH') {
      if (id === undefined) return sendJson(res, 400, { error: `method ${method} requires a resource id` });
      const idx = list.findIndex((x) => String(x.id) === id);
      if (idx === -1) return sendJson(res, 404, { error: `${resource}/${id} not found` });
      if (payload === null) return sendJson(res, 400, { error: 'JSON body required' });
      const updated =
        method === 'PUT'
          ? { ...payload, id: list[idx].id }
          : { ...list[idx], ...payload, id: list[idx].id };
      list[idx] = updated;
      return sendJson(res, 200, updated);
    }

    if (method === 'DELETE') {
      if (id === undefined) return sendJson(res, 400, { error: 'DELETE requires a resource id' });
      const idx = list.findIndex((x) => String(x.id) === id);
      if (idx === -1) return sendJson(res, 404, { error: `${resource}/${id} not found` });
      list.splice(idx, 1);
      return sendJson(res, 200, { ok: true, deleted: id });
    }

    sendJson(res, 405, { error: `method ${method} not allowed` });
  });
});

server.listen(3999, () => {
  // eslint-disable-next-line no-console
  console.log('[mock-upstream] listening on 3999');
});
